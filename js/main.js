const menuToggle = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".primary-nav");
const header = document.querySelector(".site-header");
const languageButtons = document.querySelectorAll("[data-language]");
const navLinks = document.querySelectorAll(".nav-link");
const sosButton = document.querySelector(".sos-button");
const phonePreview = document.querySelector(".phone-preview");
const descriptionMeta = document.querySelector('meta[name="description"]');

let currentLanguage = "es";

function getStoredLanguage() {
  try {
    const storedLanguage = localStorage.getItem("auxia-language");
    return storedLanguage === "en" ? "en" : "es";
  } catch {
    return "es";
  }
}

function storeLanguage(language) {
  try {
    localStorage.setItem("auxia-language", language);
  } catch {
    // The interface still works when browser storage is unavailable.
  }
}

function setLanguage(language) {
  const dictionary = translations[language] || translations.es;
  currentLanguage = language;

  document.documentElement.lang = language;
  document.title = dictionary.pageTitle;
  descriptionMeta.setAttribute("content", dictionary.pageDescription);

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  menuToggle.setAttribute("aria-label", menuToggle.getAttribute("aria-expanded") === "true" ? dictionary.closeMenu : dictionary.openMenu);
  sosButton.setAttribute("aria-label", dictionary.sosDemo);
  storeLanguage(language);
}

function closeMenu() {
  navigation.classList.remove("is-open");
  menuToggle.setAttribute("aria-expanded", "false");
  menuToggle.setAttribute("aria-label", translations[currentLanguage].openMenu);
  document.body.classList.remove("menu-open");
}

menuToggle.addEventListener("click", () => {
  const willOpen = menuToggle.getAttribute("aria-expanded") !== "true";
  navigation.classList.toggle("is-open", willOpen);
  menuToggle.setAttribute("aria-expanded", String(willOpen));
  menuToggle.setAttribute("aria-label", willOpen ? translations[currentLanguage].closeMenu : translations[currentLanguage].openMenu);
  document.body.classList.toggle("menu-open", willOpen);
});

navLinks.forEach((link) => {
  link.addEventListener("click", closeMenu);
});

const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");

document.querySelectorAll('a[href^="#"]:not(.skip-link)').forEach((link) => {
  link.addEventListener("click", (event) => {
    const target = document.querySelector(link.getAttribute("href"));
    if (!target) return;

    event.preventDefault();
    const headerOffset = header.offsetHeight + 18;
    const targetTop = target.id === "inicio"
      ? 0
      : target.getBoundingClientRect().top + window.scrollY - headerOffset;

    history.pushState(null, "", link.getAttribute("href"));
    window.scrollTo({
      top: Math.max(0, targetTop),
      behavior: reducedMotion.matches ? "auto" : "smooth"
    });
  });
});

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && navigation.classList.contains("is-open")) {
    closeMenu();
    menuToggle.focus();
  }
});

window.addEventListener("resize", () => {
  if (window.innerWidth > 920) {
    closeMenu();
  }
});

function updateHeader() {
  header.classList.toggle("is-scrolled", window.scrollY > 18);
}

window.addEventListener("scroll", updateHeader, { passive: true });
updateHeader();

const revealElements = document.querySelectorAll(".reveal");
revealElements.forEach((element) => {
  const delay = Number(element.dataset.revealDelay || 0);
  element.style.setProperty("--reveal-delay", `${delay}ms`);
});

if ("IntersectionObserver" in window) {
  const revealObserver = new IntersectionObserver(
    (entries, observer) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 }
  );

  revealElements.forEach((element) => revealObserver.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}

const navigationTargets = [...navLinks]
  .map((link) => ({ link, target: document.querySelector(link.getAttribute("href")) }))
  .filter(({ target }) => target);

function updateActiveNavigation() {
  const marker = window.scrollY + header.offsetHeight + 96;
  let activeLink = navigationTargets[0]?.link;

  navigationTargets.forEach(({ link, target }) => {
    const targetTop = target.getBoundingClientRect().top + window.scrollY;
    if (targetTop <= marker) {
      activeLink = link;
    }
  });

  if (window.innerHeight + window.scrollY >= document.documentElement.scrollHeight - 8) {
    activeLink = navigationTargets.at(-1)?.link;
  }

  navLinks.forEach((link) => {
    const isCurrent = link === activeLink;
    link.classList.toggle("is-active", isCurrent);
    if (isCurrent) {
      link.setAttribute("aria-current", "location");
    } else {
      link.removeAttribute("aria-current");
    }
  });
}

window.addEventListener("scroll", updateActiveNavigation, { passive: true });
window.addEventListener("resize", updateActiveNavigation);
updateActiveNavigation();

sosButton.addEventListener("click", () => {
  phonePreview.classList.remove("is-triggered");
  void phonePreview.offsetWidth;
  phonePreview.classList.add("is-triggered");
  sosButton.setAttribute("aria-label", translations[currentLanguage].sosConfirmed);

  window.setTimeout(() => {
    phonePreview.classList.remove("is-triggered");
    sosButton.setAttribute("aria-label", translations[currentLanguage].sosDemo);
  }, 1800);
});

document.getElementById("current-year").textContent = String(new Date().getFullYear());
setLanguage(getStoredLanguage());
